bool NativeNovatekTouch::clockOn() {
    if (!gccMapped.va) return false;
    wr32(gccMapped.va, 0x52008, rd32(gccMapped.va, 0x52008) | TM_VOTE_WRAP0_S4);
    for (unsigned poll = 0; poll < 500 && (rd32(gccMapped.va, TM_GCC_HALT_S4) & TM_CBCR_CLK_OFF); ++poll) IODelay(10);
    if (rd32(gccMapped.va, TM_S4_RCG_CMD) & TM_CMD_RCG_ROOT_OFF) {
        wr32(gccMapped.va, TM_S4_RCG_CFG, 0);          // source TCXO, divider 1, mode 0
        wr32(gccMapped.va, TM_S4_RCG_M, 0);
        wr32(gccMapped.va, TM_S4_RCG_N, 0);
        wr32(gccMapped.va, TM_S4_RCG_CMD, rd32(gccMapped.va, TM_S4_RCG_CMD) | TM_CMD_RCG_ROOT_EN | TM_CMD_RCG_UPDATE);
        for (unsigned poll = 0; poll < 500; ++poll) {
            if (!(rd32(gccMapped.va, TM_S4_RCG_CMD) & TM_CMD_RCG_ROOT_OFF)) break;
            IODelay(10);
        }
    }
    return !(rd32(gccMapped.va, TM_GCC_HALT_S4) & TM_CBCR_CLK_OFF);
}

bool NativeNovatekTouch::setPads() {
    if (!tlmmMapped.va) return false;
    const unsigned pads[4] = {TM_GPIO_MISO, TM_GPIO_MOSI, TM_GPIO_CLK, TM_GPIO_CS};
    for (unsigned i = 0; i < 4; ++i) wr32(tlmmMapped.va, tm_tlmm_ctl_reg(pads[i]), TM_PIN_SPI_CTL);
    return true;
}

bool NativeNovatekTouch::armDma() {
    dmaMemory = IOBufferMemoryDescriptor::inTaskWithPhysicalMask(kernel_task,
        static_cast<IOOptionBits>(kIODirectionInOut) | static_cast<IOOptionBits>(kIOMemoryPhysicallyContiguous),
        2 * kDmaBytes, 0xfffffff000ULL);
    if (!dmaMemory || dmaMemory->prepare() != kIOReturnSuccess) {NVT_LOG("dma memory failed"); return false;}
    addr64_t segment = 0;
    dmaPhys = dmaMemory->getPhysicalSegment(0, &segment);
    dmaVirt = static_cast<uint8_t *>(dmaMemory->getBytesNoCopy());
    if (!dmaVirt || !dmaPhys || segment < 2 * kDmaBytes) {NVT_LOG("dma memory unusable"); return false;}
    memset(dmaVirt, 0, 2 * kDmaBytes);
    cacheRange(dmaVirt, 2 * kDmaBytes, 1);
    if (!mapRegion(kAppsSmmuBase, kAppsSmmuSize, smmuMapped)) {NVT_LOG("apps-smmu map failed"); return false;}
    struct smmu_io io = {reinterpret_cast<void *>(smmuMapped.va), smmuRd, smmuWr};
    const struct smmu_plan plan = smmu_plan_bypass(&io, kQupSmmuSid, dmaPhys, 2 * kDmaBytes);
    if (plan.error) NVT_LOG("smmu bypass: %s", plan.error);
    else (void)smmu_configure_bypass(&io, &plan, kQupSmmuSid);
    // The engine reads and writes through this buffer; the two halves are its TX and RX windows.
    spi.use_dma = 1;
    spi.dma.ctx = nullptr;
    spi.dma.clean = dmaClean;
    spi.dma.clean_inval = dmaCleanInval;
    spi.dma.inval = dmaInval;
    spi.dma.tx_virt = dmaVirt;
    spi.dma.rx_virt = dmaVirt + kDmaBytes;
    spi.dma.tx_phys = dmaPhys;
    spi.dma.rx_phys = dmaPhys + kDmaBytes;
    spi.dma.size = kDmaBytes;
    return plan.error == nullptr;
}

bool NativeNovatekTouch::openBus() {
    if (!clockOn()) {NVT_LOG("SE4 clock did not come up"); return false;}
    if (!setPads()) {NVT_LOG("TLMM pads unavailable"); return false;}
    spi.se.ctx = reinterpret_cast<void *>(se);
    spi.se.rd = ioRd;
    spi.se.wr = ioWr;
    spi.se.delay_us = ioDelayUs;
    spi.wrapper.ctx = reinterpret_cast<void *>(wrapper);
    spi.wrapper.rd = ioRd;
    spi.poll_limit = 200000;
    spi.poll_only = 2;
    spi.allow_fifo_disabled = 1;
    spi.use_dma = 0;
    if (!armDma()) return false;
    int rc = geni_spi_init(&spi);
    if (rc == 0) rc = geni_spi_set_clock(&spi, 400000, TM_SPI_HZ, 0);
    if (rc == 0) rc = geni_spi_setup(&spi, 0, 0);
    if (rc) {NVT_LOG("geni init/clock/setup rc=%d", rc); return false;}
    return true;
}

// Exactly the sequence stages 33-35 proved: id from ROM, then the host firmware download, then the three
// scan commands. The download's last handshake lives in the event buffer, and the ROM's ENB_CASC answer is
// not trustworthy, so a failed download is retried once with the other map.
bool NativeNovatekTouch::bringUp() {
    tx = static_cast<uint8_t *>(IOMalloc(NVT_TRANSFER_LEN + 8));
    rx = static_cast<uint8_t *>(IOMalloc(NVT_READ_MAX + 2));
    if (!tx || !rx) {NVT_LOG("bus buffers failed"); return false;}
    memset(&chip, 0, sizeof chip);
    memset(&bus, 0, sizeof bus);
    csb.se = se;
    csb.spi = &spi;
    bus.ctx = &csb;
    bus.xfer = csBusXfer;
    bus.delay_ms = busDelayMs;
    chip.bus = &bus;
    chip.scratch = tx;
    chip.rxbuf = rx;

    if (!openBus()) return false;
    const int idRc = nvt_identify(&chip);
    NVT_LOG("id rc=%d %02x%02x%02x%02x%02x%02x cascade=%d", idRc, chip.id[0], chip.id[1], chip.id[2], chip.id[3],
        chip.id[4], chip.id[5], chip.cascade);
    if (idRc) return false;

    const unsigned imageSize = &native_touch_firmware_size ? native_touch_firmware_size : 0;
    if (!&native_touch_firmware || !&native_touch_firmware_size || !imageSize) {
        NVT_LOG("no firmware object in this kernel (.cache/firmware/novatek/)");
        return false;
    }
    struct nvt_fw fw;
    memset(&fw, 0, sizeof fw);
    const int parseRc = nvt_fw_parse(&fw, native_touch_firmware, imageSize);
    if (parseRc || fw.count < 2) {NVT_LOG("firmware image rejected rc=%d parts=%u", parseRc, fw.count); return false;}
    chip.reset_retries = 60;                       // the vendor waits 10 polls of 10 ms; 60 tells slow from never
    int dl = nvt_download_firmware(&chip, &fw);
    NVT_LOG("download rc=%d stage=%u try=%u polls=%u", dl, chip.dl_stage, chip.dl_attempt, chip.dl_polls);
    if (dl) {
        nvt_use_map(&chip, 1, !chip.cascade);
        dl = nvt_download_firmware(&chip, &fw);
        NVT_LOG("download retry rc=%d stage=%u polls=%u", dl, chip.dl_stage, chip.dl_polls);
        if (dl) return false;
    }
    struct nvt_fw_info info;
    if (nvt_get_fw_info(&chip, &info)) {NVT_LOG("firmware info unreadable"); return false;}
    NVT_LOG("firmware v=%02x type=%02x nodes=%ux%u panel=%ux%u pid=%04x", info.fw_ver, info.fw_type,
        info.x_num, info.y_num, info.abs_x_max, info.abs_y_max, info.pid);
    const int baseline = nvt_set_custom_cmd(&chip, 0x19, 0x0000);
    const int doze = nvt_set_doze_delay(&chip, 120);
    const int scan = nvt_set_custom_cmd(&chip, 0x01, 0x0002);
    if (baseline || scan) {NVT_LOG("scan command failed %d/%d", baseline, scan); return false;}
    if (doze) NVT_LOG("doze delay write returned %d", doze);
    return true;
}

void NativeNovatekTouch::pump() {
    uint8_t *frame = static_cast<uint8_t *>(IOMalloc(NVT_THP_FRAME_LEN + 1));
    int16_t *matrix = static_cast<int16_t *>(IOMalloc(NVT_NODES * sizeof(int16_t)));
    if (!frame || !matrix) {NVT_LOG("frame buffers failed"); return;}
    struct nvt_contact contacts[NVT_SLOTS];
    unsigned lastCounter = 0xffffffffu, frames = 0, contactsSeen = 0, published = 0, errors = 0, lastLog = 0;
    bool down = false;
    NVT_LOG("pumping at %u kHz", TM_SPI_HZ / 1000);
    while (!quit) {
        uint8_t header[NVT_THP_PEEK_LEN];
        if (nvt_peek_frame_header(&chip, header)) {
            ++errors;
            if (errors == 1) NVT_LOG("peek failed");
            IOSleep(10);
            continue;
        }
        if (!nvt_peek_valid(header)) {IOSleep(2); continue;}
        const unsigned counter = nvt_peek_counter(header);
        if (counter == lastCounter) {IOSleep(2); continue;}
        lastCounter = counter;
        const unsigned type = nvt_peek_type(header);
        if (type != 2 && type != 4) continue;
        if (nvt_read_frame(&chip, frame) || !nvt_frame_header_valid(frame)) {++errors; continue;}
        ++frames;
        nvt_frame_matrix(frame, matrix);
        const int n = nvt_touch_process(core, matrix, type, contacts, NVT_SLOTS);
        if (n > 0) {
            ++contactsSeen;
            native_touch_publish(contacts, static_cast<unsigned>(n));
            ++published;
            down = true;
        } else if (n == 0 && down) {
            native_touch_publish(nullptr, 0);      // finger up
            down = false;
        }
        if (frames - lastLog >= 3000) {            // ~30 s at the measured ~100 fps
            lastLog = frames;
            NVT_LOG("frames=%u contacts=%u published=%u errors=%u hid=%u sink=%d", frames, contactsSeen, published,
                errors, native_touch_hid_reports, native_touch_sink_ready());
        }
    }
    IOFree(frame, NVT_THP_FRAME_LEN + 1);
    IOFree(matrix, NVT_NODES * sizeof(int16_t));
    pumpRunning = false;
    NVT_LOG("pump stopped");
}

void NativeNovatekTouch::pumpEntry(void *self, int) {
    NativeNovatekTouch *driver = static_cast<NativeNovatekTouch *>(self);
    if (driver) driver->pump();
    thread_terminate(current_thread());
}

bool NativeNovatekTouch::start(IOService *provider) {
    (void)provider;
    if (!mapRegion(TM_GCC_BASE, 0x200000, gccMapped) ||
        !mapRegion(TM_TLMM_BASE, 0x200000, tlmmMapped) ||
        !mapRegion(TM_QUP_WINDOW_BASE, TM_QUP_WINDOW_SIZE, qupMapped)) {
        NVT_LOG("register window mapping failed");
        return false;
    }
    se = qupMapped.va + TM_QUP_SE_OFFSET;
    wrapper = qupMapped.va + TM_QUP_WRAP_OFFSET;
    core = static_cast<struct nvt_touch_core *>(IOMalloc(sizeof *core));
    if (!core) {NVT_LOG("touch core allocation failed"); return false;}
    nvt_touch_reset(core);

    // The panel needs the boot to have settled: the display client presents and the UFS root is up by then,
    // and the pump competes with neither. muyu-touch-delay overrides (seconds, capped at 10 min).
    unsigned delay = 45;
    PE_parse_boot_argn("muyu-touch-delay", &delay, sizeof delay);
    if (delay > 600) delay = 600;
    if (delay) IOSleep(delay * 1000);
    if (quit) return false;
    if (!bringUp()) {NVT_LOG("bring-up failed"); return false;}
    if (geni_spi_set_clock(&spi, TM_SPI_HZ, TM_SPI_HZ, 0)) {NVT_LOG("19.2 MHz clock failed"); return false;}

    if (kernel_thread_start(static_cast<thread_continue_t>(pumpEntry), this, &pumpThread) != KERN_SUCCESS) {
        NVT_LOG("pump thread failed");
        return false;
    }
    thread_deallocate(pumpThread);
    pumpRunning = true;
    registerService();
    NVT_LOG("started");
    return true;
}

void NativeNovatekTouch::stop(IOService *provider) {
    quit = true;
    if (pumpThread) {
        for (unsigned i = 0; i < 200 && pumpRunning; ++i) IOSleep(10);
        thread_deallocate(pumpThread);
        pumpThread = nullptr;
    }
    IOService::stop(provider);
}

void NativeNovatekTouch::free() {
    if (core) {IOFree(core, sizeof *core); core = nullptr;}
    if (tx) {IOFree(tx, NVT_TRANSFER_LEN + 8); tx = nullptr;}
    if (rx) {IOFree(rx, NVT_READ_MAX + 2); rx = nullptr;}
    if (dmaMemory) {
        if (dmaVirt) dmaMemory->complete();
        dmaMemory->release();
        dmaMemory = nullptr;
    }
    Region *regions[4] = {&gccMapped, &tlmmMapped, &qupMapped, &smmuMapped};
    for (unsigned i = 0; i < 4; ++i) {
        if (regions[i]->keep) {regions[i]->keep->release(); regions[i]->keep = nullptr; regions[i]->va = 0;}
    }
    IOService::free();
}

NativeNovatekTouch *NativeNovatekTouch::create() {
    NativeNovatekTouch *driver = new NativeNovatekTouch;
    if (!driver || !driver->init()) {
        if (driver) driver->release();
        return nullptr;
    }
    IOService *platform = static_cast<IOService *>(IOService::getPlatform());
    if (!platform || !driver->attach(platform) || !driver->start(platform)) {
        if (driver->getProvider()) driver->detach(platform);
        driver->release();
        return nullptr;
    }
    return driver;
}

extern "C" IOService *native_novatek_touch_start(void);
extern "C" IOService *native_novatek_touch_start(void) {
    unsigned enabled = 0;
    if (!PE_parse_boot_argn("muyu-touch-drv", &enabled, sizeof enabled) || !enabled) return nullptr;
    static IOService *service;
    if (service) return service;
    service = NativeNovatekTouch::create();
    NVT_LOG("driver object %s", service ? "started" : "not started");
    return service;
}
