// NativeNovatekTouch: the production NT36532E touch driver for muyu.
//
// Until 2026-10-26 the working touch path was a kernel thread started from the display probe
// (package/TouchProbeMuyu.cpp, muyu-touch-drv=1). It works, but it owns no object: the mappings, the DMA
// buffer, the NVT chip state and the thread are all globals of a diagnostic file, stop() does not exist,
// and the bring-up sequence is only reachable from that probe. This file is the same sequence as a real
// IOService: start() maps and brings the part up, then spawns the pump thread; stop() asks the pump to
// leave; the object is attached to the platform expert and registered, so it appears in the IORegistry
// like any other driver on this board.
//
// Everything in here was proved on hardware between 2026-10-25 and 2026-10-26 (docs/TOUCH-PORT.md
// §27-§33): GCC vote + SE4 RCG, the four SPI pads to mux 1 (0x184), SE DMA behind an apps-SMMU bypass,
// GENI init at 400 kHz for the download and 19.2 MHz for frames, nvt_identify, the host firmware download
// (with the event-buffer map retry), nvt_start_scanning, and a 32-byte THP header poll that reads a whole
// frame only when the counter moves. Contacts go out through native_touch_publish(), the seqlock
// NativeHidInput reads; the digitizer collection must live on the *keyboard* HID service, never on a
// separate digitizer-only service (that one never dispatches: TOUCH-PORT §32).
//
// What this driver deliberately does not do yet: the pin interrupt (gpio54 armed but never fired, and it
// stopped the panel's frame counter - TOUCH-PORT §33), and the vendor o81 firmware (the public NT36532E
// image is embedded today; see .cache/firmware/novatek/PROVENANCE.md).
