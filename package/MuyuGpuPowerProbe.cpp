struct Window {
    uint64_t physical;
    uint64_t bytes;
    IOMemoryDescriptor *descriptor;
    IOMemoryMap *map;
    volatile uint8_t *base;
};

// The device tree's kgsl-smmu reg is 0x3da0000+0x40000; the board sequence only reads GR0,
// but a context bank lives at 0x20000+bank*0x1000, so mode 9 maps the whole aperture.
constexpr uint64_t kSmmuWindow = 0x40000;

Window gWindows[6] = {
    {MGB_GCC_GPU_PAGE, 0x1000, nullptr, nullptr, nullptr},
    {MGB_GCC_VOTE_PAGE, 0x1000, nullptr, nullptr, nullptr},
    {MGB_GPUCC_BASE, MGB_GPUCC_SIZE, nullptr, nullptr, nullptr},
    {MGB_SMMU_BASE, kSmmuWindow, nullptr, nullptr, nullptr},
    {MGB_GPU_BASE, MGB_GPU_WINDOW, nullptr, nullptr, nullptr},
    {MUYU_RSC_DRV2_BASE, MUYU_RSC_DRV2_BYTES, nullptr, nullptr, nullptr},   // window 5: RSC drv@2
};

bool mapWindow(unsigned index) {
    Window &w = gWindows[index];
    if (w.base) return true;
    w.descriptor = IOMemoryDescriptor::withPhysicalAddress(w.physical, (IOByteCount)w.bytes, kIODirectionInOut);
    if (!w.descriptor) return false;
    w.map = w.descriptor->map(kIOMapAnywhere);
    if (!w.map) {
        OSSafeReleaseNULL(w.descriptor);
        return false;
    }
    w.base = reinterpret_cast<volatile uint8_t *>(w.map->getVirtualAddress());
    return w.base != nullptr;
}

int read32(void *, unsigned window, uint32_t offset, uint32_t *out) {
    if (window > MUYU_RSC_WINDOW || !out || !gWindows[window].base) return -1;
    if (offset & 3 || (uint64_t)offset + 4 > gWindows[window].bytes) return -1;
    *out = *reinterpret_cast<volatile uint32_t *>(gWindows[window].base + offset);
    return 0;
}

int write32(void *, unsigned window, uint32_t offset, uint32_t value) {
    if (window > MUYU_RSC_WINDOW || !gWindows[window].base) return -1;
    if (offset & 3 || (uint64_t)offset + 4 > gWindows[window].bytes) return -1;
    *reinterpret_cast<volatile uint32_t *>(gWindows[window].base + offset) = value;
    return 0;
}

void delayUs(void *, unsigned us) { IODelay(us); }

const char *yesNo(int v) { return v ? "Y" : "N"; }

// ArmSmmu4KIo peer over window 3 (the full SMMU aperture). Offsets are the SMMU's own,
// relative to MGB_SMMU_BASE, exactly as ArmSmmu4KProgram expects them.
int smmuRead32(void *, size_t at, uint32_t *out) {
    if (!out || (at & 3) || at + 4 > kSmmuWindow) return 1;
    *out = *reinterpret_cast<volatile uint32_t *>(gWindows[MGB_WIN_SMMU].base + at);
    return 0;
}
int smmuRead64(void *, size_t at, uint64_t *out) {
    uint32_t low = 0, high = 0;
    if (!out || (at & 7) || at + 8 > kSmmuWindow) return 1;
    if (smmuRead32(nullptr, at, &low) || smmuRead32(nullptr, at + 4, &high)) return 1;
    *out = ((uint64_t)high << 32) | low;
    return 0;
}
int smmuWrite32(void *, size_t at, uint32_t v) {
    if ((at & 3) || at + 4 > kSmmuWindow) return 1;
    *reinterpret_cast<volatile uint32_t *>(gWindows[MGB_WIN_SMMU].base + at) = v;
    return 0;
}
int smmuWrite64(void *, size_t at, uint64_t v) {
    if ((at & 7) || at + 8 > kSmmuWindow) return 1;
    return smmuWrite32(nullptr, at, (uint32_t)v) | smmuWrite32(nullptr, at + 4, (uint32_t)(v >> 32));
}
int smmuBarrier(void *) { __asm__ volatile("dsb sy" ::: "memory"); return 0; }

// The five GMU windows ShengGmuBindMmio() requires, verbatim from the generated
// ShengGmuSource.h (sheng_gmu_window_physical/bytes): core, rscc, pdc, gpu, cx_misc.
// Mode 10 only reads them; mode 11 uses the same mappings for the cold start.
/* MGW_CMDDB keeps its bit position so mode 10's "mapped=31" means the same thing; the
 * GPU window (GBIF/QSB writes in the cold start) is only mapped by mode 11. */
enum { MGW_CORE = 0, MGW_RSCC, MGW_PDC, MGW_CXMISC, MGW_CMDDB, MGW_GPU, MGW_COUNT };
struct GmuWindow {
    uint64_t physical;
    uint64_t bytes;
    IOMemoryDescriptor *descriptor;
    IOMemoryMap *map;
    volatile uint8_t *base;
};
GmuWindow gGmuWindows[MGW_COUNT] = {
    {0x3d68000, 0x37000, nullptr, nullptr, nullptr},   // GMU core (CM3/HFI), ShengGmuCore
    {0x3d50000, 0x10000, nullptr, nullptr, nullptr},   // RSCC
    {0xb280000, 0x10000, nullptr, nullptr, nullptr},   // GPU PDC
    {0x3d9e000, 0x1000, nullptr, nullptr, nullptr},    // CX misc (TCM retention)
    {0x81c60000, 0x20000, nullptr, nullptr, nullptr},  // AOP cmd-db (RAM, not MMIO)
    {0x3d00000, 0x40000, nullptr, nullptr, nullptr},   // GPU window (GBIF/QSB), mode 11 only
};

bool mapGmuWindow(unsigned index) {
    GmuWindow &w = gGmuWindows[index];
    if (w.base) return true;
    w.descriptor = IOMemoryDescriptor::withPhysicalAddress(w.physical, (IOByteCount)w.bytes,
                                                           kIODirectionInOut);
    if (!w.descriptor) return false;
    w.map = w.descriptor->map(kIOMapAnywhere);
    if (!w.map) {
        OSSafeReleaseNULL(w.descriptor);
        return false;
    }
    w.base = reinterpret_cast<volatile uint8_t *>(w.map->getVirtualAddress());
    return w.base != nullptr;
}

int gmuRead32(unsigned window, uint32_t offset, uint32_t *out) {
    if (window >= MGW_COUNT || !out || (offset & 3) ||
        (uint64_t)offset + 4 > gGmuWindows[window].bytes) return -1;
    *out = *reinterpret_cast<volatile uint32_t *>(gGmuWindows[window].base + offset);
    return 0;
}

// Clean the range to the point of coherency before the SMMU walks it and before the GMU
// reads the staged image. A barrier alone is not a cache clean (ArmSmmu4KLiveVisibility).
int publishCache(void *, uint64_t physical, size_t bytes) {
    if (!physical || !bytes || (bytes & 4095) || (physical & 4095)) return 1;
    flush_dcache64((addr64_t)physical, (unsigned)bytes, TRUE);
    __asm__ volatile("dsb sy" ::: "memory");
    return 0;
}

// ---- mode 11: the cold start's own window bindings -------------------------------
// ShengGmu.c indexes its windows in ShengGmuSource.h order (core, rscc, pdc, gpu,
// cx_misc), which is not the MGW_* order. Keep the translation explicit and let the
// generated physical/byte tables be the authority (same contract as ShengGmuBindMmio).
volatile uint8_t *gColdBase[ShengGmuWindows] = {nullptr, nullptr, nullptr, nullptr, nullptr};
uint64_t gColdPhysical[ShengGmuWindows] = {0, 0, 0, 0, 0};
// The five GMU extents as mode 7 allocated them: coldBarrier() flushes exactly these.
uint64_t gmuGmuExtentPhysical[5] = {0, 0, 0, 0, 0};
unsigned long gmuGmuExtentBytes[5] = {0, 0, 0, 0, 0};

int coldMapWindows() {
    static const unsigned mgw[ShengGmuWindows] = {MGW_CORE, MGW_RSCC, MGW_PDC, MGW_GPU, MGW_CXMISC};
    for (unsigned i = 0; i < ShengGmuWindows; ++i) {
        const GmuWindow &w = gGmuWindows[mgw[i]];
        if (!w.base) return 1;
        if (w.physical != sheng_gmu_window_physical[i] || w.bytes != sheng_gmu_window_bytes[i])
            return 1;   // the mapping is not the pinned DT range: refuse before any write
        gColdBase[i] = w.base;
        gColdPhysical[i] = w.physical;
    }
    return 0;
}

// mode 12's OOB accessor: the GMU core window, indexed by a6xx dword offsets exactly as
// ShengGmu.c does (word * 4 - CORE_GPU_DELTA). Bounds and errors come from coldRead32/Write32.
int coldRead32(void *, unsigned window, size_t at, uint32_t *out);
int coldWrite32(void *, unsigned window, size_t at, uint32_t value);
size_t gxByteOffset(uint32_t dword) {
    return (size_t)dword * 4u - SHENG_GMU_CORE_GPU_DELTA;
}

int gxRead(void *, uint32_t dword, uint32_t *out) {
    return coldRead32(nullptr, ShengGmuCore, gxByteOffset(dword), out);
}

int gxWrite(void *, uint32_t dword, uint32_t value) {
    return coldWrite32(nullptr, ShengGmuCore, gxByteOffset(dword), value);
}

void gxDelay(void *, unsigned us) { IODelay(us); }

int coldRead32(void *, unsigned window, size_t at, uint32_t *out) {
    if (window >= ShengGmuWindows || !out || (at & 3) ||
        at + 4 > (size_t)sheng_gmu_window_bytes[window] || !gColdBase[window]) return 1;
    *out = *reinterpret_cast<volatile uint32_t *>(gColdBase[window] + at);
    return 0;
}

int coldWrite32(void *, unsigned window, size_t at, uint32_t value) {
    if (window >= ShengGmuWindows || (at & 3) ||
        at + 4 > (size_t)sheng_gmu_window_bytes[window] || !gColdBase[window]) return 1;
    *reinterpret_cast<volatile uint32_t *>(gColdBase[window] + at) = value;
    return 0;
}

// The GMU reads its icache image and the HFI queues through the SMMU (Normal
// non-cacheable on the device side), so the CPU's dirty lines have to reach the point
// of coherency before the CM3 is released -- and after every HFI queue update. This is
// the same publication publishCache() does for the page tables, applied to the five GMU
// extents. ShengGmu.c calls the I/O barrier exactly between the payload copy and the
// reset release, which is why the flush lives here rather than in the caller.
int coldBarrier(void *) {
    for (unsigned i = 0; i < 5; ++i)
        if (gmuGmuExtentPhysical[i] && gmuGmuExtentBytes[i])
            flush_dcache64((addr64_t)gmuGmuExtentPhysical[i], (unsigned)gmuGmuExtentBytes[i], TRUE);
    __asm__ volatile("dsb sy" ::: "memory");
    return 0;
}

int coldSha256(void *, const void *data, size_t bytes, uint8_t digest[32]) {
    SHA256_CTX ctx;
    SHA256_Init(&ctx);
    SHA256_Update(&ctx, data, bytes);
    SHA256_Final(digest, &ctx);
    return 0;
}

// Monotonic microseconds. ShengGmu.c bounds every poll by 10 ms of this clock, so it
// must be a real clock and not a tick counter with a coarse granularity.
int coldNowUs(void *, uint64_t *value) {
    uint64_t uptime = 0, nanos = 0;
    if (!value) return 1;
    clock_get_uptime(&uptime);
    absolutetime_to_nanoseconds(uptime, &nanos);
    *value = nanos / 1000;
    return 0;
}

int coldWaitUs(void *, unsigned us) { IODelay(us); return 0; }

