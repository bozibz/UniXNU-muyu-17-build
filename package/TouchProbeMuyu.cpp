// Stage 20: the controller does not answer, so sweep what the host side can still get wrong, in one
// boot: SPI mode 0..3 x 100 kHz / 1 MHz / 19.2 MHz, every transfer wrapped in CS assert/deassert.
// The engine itself is known good (stage 19 loopback), so a live controller should answer at least
// one of these twelve combinations.
void matrixStage(Survey &s) {
    static const unsigned speeds[3] = {100000, 1000000, 19200000};
    IOBufferMemoryDescriptor *mem = IOBufferMemoryDescriptor::inTaskWithPhysicalMask(kernel_task,
        static_cast<IOOptionBits>(kIODirectionInOut) | static_cast<IOOptionBits>(kIOMemoryPhysicallyContiguous),
        2 * kDmaBytes, 0xfffffff000ULL);
    if (!mem || mem->prepare() != kIOReturnSuccess) {row("mx mem failed"); return;}
    addr64_t segLen = 0;
    const uint64_t dmaPhys = mem->getPhysicalSegment(0, &segLen);
    uint8_t *const virt = static_cast<uint8_t *>(mem->getBytesNoCopy());
    if (!virt || !dmaPhys || segLen < 2 * kDmaBytes) {row("mx mem unusable"); return;}
    memset(virt, 0, 2 * kDmaBytes);
    cacheRange(virt, 2 * kDmaBytes, 1);
    static Region smmu;
    if (!mapRegion(TM_APPS_SMMU_BASE, TM_APPS_SMMU_SIZE, smmu)) {row("mx smmu map failed"); return;}
    struct smmu_io io = {reinterpret_cast<void *>(smmu.va), smmuRd, smmuWr};
    const struct smmu_plan plan = smmu_plan_bypass(&io, TM_QUP_SMMU_SID, dmaPhys, 2 * kDmaBytes);
    if (!plan.error) {smmu_configure_bypass(&io, &plan, TM_QUP_SMMU_SID);}
    row("mx smmu err=%s", plan.error ? plan.error : "none");

    s.spi.use_dma = 1;
    s.spi.dma.ctx = nullptr;
    s.spi.dma.clean = dmaClean;
    s.spi.dma.clean_inval = dmaCleanInval;
    s.spi.dma.inval = dmaInval;
    s.spi.dma.tx_virt = virt;
    s.spi.dma.rx_virt = virt + kDmaBytes;
    s.spi.dma.tx_phys = dmaPhys;
    s.spi.dma.rx_phys = dmaPhys + kDmaBytes;
    s.spi.dma.size = kDmaBytes;
    const int initRc = geni_spi_init(&s.spi);
    row("mx init rc=%d fifo_dis=%d", initRc, s.spi.info.fifo_disabled);
    if (initRc != 0) return;

    static uint8_t tx[NVT_TRANSFER_LEN + 8], rx[NVT_READ_MAX + 2];
    static CsBus csbus;
    csbus.se = s.se;
    csbus.spi = &s.spi;
    for (unsigned m = 0; m < 4; ++m) {
        geni_spi_setup(&s.spi, m, 0);
        for (unsigned k = 0; k < 3; ++k) {
            const int crc = geni_spi_set_clock(&s.spi, speeds[k], TM_SPI_HZ, 0);
            struct nvt_chip chip;
            memset(&chip, 0, sizeof chip);
            struct nvt_bus bus;
            memset(&bus, 0, sizeof bus);
            bus.ctx = &csbus;
            bus.xfer = [](void *ctx, const uint8_t *o, uint8_t *i, size_t n) -> int {
                CsBus *b = static_cast<CsBus *>(ctx);
                if (csCommand(b->se, TM_SPI_CS_ASSERT)) {return -1;}
                const int r = geni_spi_transfer(b->spi, o, i, n, 1);
                csCommand(b->se, TM_SPI_CS_DEASSERT);
                return r ? -1 : 0;
            };
            bus.delay_ms = [](void *, unsigned ms) {IOSleep(ms);};
            chip.bus = &bus;
            chip.scratch = tx;
            chip.rxbuf = rx;
            const int rc = (crc == 0) ? nvt_identify(&chip) : -1;
            row("mx mode%u %ukhz clkrc=%d rc=%d id=%02x %02x %02x %02x %02x %02x", m, speeds[k] / 1000, crc,
                rc, (unsigned)chip.id[0], (unsigned)chip.id[1], (unsigned)chip.id[2], (unsigned)chip.id[3],
                (unsigned)chip.id[4], (unsigned)chip.id[5]);
            if (rc == 0) return;   // found it: stop the sweep
        }
    }
    geni_spi_setup(&s.spi, 0, 0);
}

// Stage 21: is anything on the controller side driving the pads?
//
// Put the MISO / CS / IRQ pads into GPIO input with a pull-up and then with a pull-down and read the
// pad: a pad that follows the pull (up=1, down=0) is floating, i.e. nothing on the other end drives it
// (controller unpowered, in reset, or not selected and high-Z). pinctrl-msm encodes pull in bits [1:0]:
// 1 = pull-down, 3 = pull-up; drive is bits [8:6], mux bits [4:2].
void padLevelStage(Survey &s) {
    static const struct {unsigned gpio; const char *name;} pads[] = {
        {16, "miso"}, {17, "mosi"}, {19, "cs"}, {54, "irq"}, {26, "lcdid"}};
    for (unsigned i = 0; i < sizeof pads / sizeof pads[0]; ++i) {
        const unsigned g = pads[i].gpio;
        const uint32_t saved = rd32(s.tlmm.va, 0x1000u * g);
        wr32(s.tlmm.va, 0x1000u * g, (3u << 0) | (6u << 6));   // GPIO input, pull-up
        IODelay(100);
        const unsigned up = rd32(s.tlmm.va, 0x1000u * g + 4) & 1u;
        wr32(s.tlmm.va, 0x1000u * g, (1u << 0) | (6u << 6));   // GPIO input, pull-down
        IODelay(100);
        const unsigned down = rd32(s.tlmm.va, 0x1000u * g + 4) & 1u;
        wr32(s.tlmm.va, 0x1000u * g, saved);
        row("pad %s gpio%u ctl0=%08x up=%u down=%u", pads[i].name, g, saved, up, down);
    }
}

