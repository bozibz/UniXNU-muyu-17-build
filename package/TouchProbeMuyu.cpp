// SCM (TrustZone) IO: Mu-Silicium's own SIP interface header documents the service we need:
//   TZ_IO_ACCESS_READ_ID  = TZ_SYSCALL_CREATE_SMC_ID(OWNER_SIP=2, SVC_IO_ACCESS=5, 0x01) = 0x02000501
//   TZ_IO_ACCESS_WRITE_ID = ... 0x02 = 0x02000502
// "Allows reading/writing of memory areas that fall under Memory/Area/Register Protection Unit (xPU)
// protection but do not need to be secured" - which is exactly the TLMM on this board. Two call
// conventions are in use on Qualcomm firmware, so both are tried, reads only:
//   A  the Linux qcom_scm "SCM device" one: a0 = (svc << 8) | cmd, a5 = arginfo (nargs), result in a1
//   B  the firmware param-id one: a0 = owner << 24 | svc << 8 | cmd, a1 = param id, then the args,
//      with out parameters passed as physical pointers (here: into the DMA buffer).

// Stage 15: a tiny scripted TLMM access, chosen by boot arguments, so a fault costs one boot:
//   muyu-touch-rd=<offset>   read 0xf000000+offset and print it
//   muyu-touch-wr=<value>    write it back to the same offset first, then read it again
//   muyu-touch-rd2=<offset>  a second read, after that (put the likely-fatal one here)
// gpio0 reads fine (01000001, survived) while the GPIOs of the DT's tlmm-vm-gpio-list reset the
// board, so the next questions are: does a GPIO outside that list read and write, and is it only the
// ctl page that is locked?
void tlmmReadStage(Survey &s) {
    unsigned rd = 0, wr = 0, rd2 = 0;
    PE_parse_boot_argn("muyu-touch-rd", &rd, sizeof(rd));
    PE_parse_boot_argn("muyu-touch-wr", &wr, sizeof(wr));
    PE_parse_boot_argn("muyu-touch-rd2", &rd2, sizeof(rd2));
    Region tlmm;
    if (!mapRegion(0x0f000000ULL, 0x40000ULL, tlmm)) {row("tlmm map failed"); return;}
    row("tlmm read +%x = %08x (survived)", rd, rd32(tlmm.va, rd));
    if (wr) {
        wr32(tlmm.va, rd, wr);
        IODelay(200);
        row("tlmm wrote %08x to +%x, read back %08x", wr, rd, rd32(tlmm.va, rd));
    }
    if (rd2) {
        row("tlmm read +%x = %08x (survived)", rd2, rd32(tlmm.va, rd2));
    }
}

// Stage 17: bit-bang the four SPI pins through the pin controller, without the GENI engine.
//
// gpio16-19 are already muxed to qup0_se4_lN by the bootloader (ctl = 0x184), the GENI engine says
// every DMA transfer completed, and the chip id still reads 0x00. So either the controller is not
// answering (power/reset) or the engine never shifted anything. Toggling the pins by hand separates
// the two: with CS low the controller must drive MISO while the clock runs.
// ctl layout on cliffs (pinctrl-cliffs.c): mux [4:2], pull [1:0], drive [8:6], output enable bit 9.
// io layout: bit 0 = input level, bit 1 = output level.
void bitBangStage(Survey &s) {
    const uint32_t out_ctl = (6u << 6) | (1u << 9);
    const uint32_t in_ctl = (6u << 6);
    uint32_t save[4];
    for (unsigned i = 0; i < 4; ++i) save[i] = rd32(s.tlmm.va, 0x1000u * (16 + i));

    auto setLevel = [&](unsigned gpio, bool high) {
        uint32_t v = rd32(s.tlmm.va, 0x1000u * gpio + 4);
        v = high ? (v | 2u) : (v & ~2u);
        wr32(s.tlmm.va, 0x1000u * gpio + 4, v);
    };

    wr32(s.tlmm.va, 0x1000u * 18, out_ctl);   // CLK
    wr32(s.tlmm.va, 0x1000u * 17, out_ctl);   // MOSI
    wr32(s.tlmm.va, 0x1000u * 19, out_ctl);   // CS
    wr32(s.tlmm.va, 0x1000u * 16, in_ctl);    // MISO
    setLevel(18, false);
    setLevel(17, false);
    setLevel(19, true);
    IODelay(100);
    row("bb idle: ctl %08x %08x %08x %08x miso=%u", rd32(s.tlmm.va, 0x1000u * 16), rd32(s.tlmm.va, 0x1000u * 17),
        rd32(s.tlmm.va, 0x1000u * 18), rd32(s.tlmm.va, 0x1000u * 19), rd32(s.tlmm.va, 0x1000u * 16 + 4) & 1u);

    // CS low, clock 32 bits of 0xff out (all ones -> the controller sees no valid opcode, but it must
    // still drive MISO if it is alive and selected), sample MISO on the rising edge.
    setLevel(19, false);
    IODelay(5);
    uint32_t rx = 0;
    unsigned miso_cs_low = 0;
    for (unsigned n = 0; n < 32; ++n) {
        setLevel(17, true);
        IODelay(1);
        setLevel(18, true);
        IODelay(1);
        rx = (rx << 1) | (rd32(s.tlmm.va, 0x1000u * 16 + 4) & 1u);
        miso_cs_low += rd32(s.tlmm.va, 0x1000u * 16 + 4) & 1u;
        setLevel(18, false);
        IODelay(1);
    }
    setLevel(19, true);
    IODelay(5);
    const unsigned miso_cs_high = rd32(s.tlmm.va, 0x1000u * 16 + 4) & 1u;
    row("bb cs low: miso bits=%u rx32=%08x cs high miso=%u", miso_cs_low, rx, miso_cs_high);

    for (unsigned i = 0; i < 4; ++i) wr32(s.tlmm.va, 0x1000u * (16 + i), save[i]);
    row("bb pins restored %08x %08x %08x %08x", save[0], save[1], save[2], save[3]);
}

// Stage 18: does chip select actually reach the chip?
//
// The DMA path proves the engine clocks and receives a low MISO, so the controller is either not
// selected or not powered. The pad's input path stays readable while the pin is muxed to the
// peripheral, so: assert CS through the engine and read gpio19's level, then deassert and read again.
// If the level follows the command, CS works and the controller simply does not answer.
void csLevelStage(Survey &s) {
    auto level = [&](unsigned gpio) { return rd32(s.tlmm.va, 0x1000u * gpio + 4) & 1u; };
    row("cs idle: miso=%u mosi=%u clk=%u cs=%u", level(16), level(17), level(18), level(19));
    const int a = csCommand(s.se, TM_SPI_CS_ASSERT);
    IODelay(50);
    row("cs asserted(rc=%d): miso=%u mosi=%u clk=%u cs=%u", a, level(16), level(17), level(18), level(19));
    const int d = csCommand(s.se, TM_SPI_CS_DEASSERT);
    IODelay(50);
    row("cs deasserted(rc=%d): miso=%u mosi=%u clk=%u cs=%u", d, level(16), level(17), level(18), level(19));
    row("cs ctl now %08x %08x %08x %08x", rd32(s.tlmm.va, 0x1000u * 16), rd32(s.tlmm.va, 0x1000u * 17),
        rd32(s.tlmm.va, 0x1000u * 18), rd32(s.tlmm.va, 0x1000u * 19));
}

// DMA: the sample boards reach memory through the apps SMMU with a pass-through stream, which is the
// same mapping the UFS driver installs (docs/native-ufs.md). The wrapper is marked dma-coherent, but
// the engine's view is still made coherent explicitly.
constexpr size_t kDmaBytes = 64 * 1024;
constexpr uint64_t TM_APPS_SMMU_BASE = 0x15000000ULL;   // DT apps-smmu@15000000 (1 MiB of registers)
constexpr uint64_t TM_APPS_SMMU_SIZE = 0x100000ULL;
constexpr uint16_t TM_QUP_SMMU_SID = 0xa3;              // DT qupv3_0_geni_se@ac0000: iommus = <&apps_smmu 0xa3 0>

void cacheRange(void *p, size_t len, int op) {   // 0 clean, 1 clean+invalidate, 2 invalidate
    uint64_t ctr;
    __asm__ volatile("mrs %0, ctr_el0" : "=r"(ctr));
    size_t line = 4u << ((ctr >> 16) & 15);
    uintptr_t a = reinterpret_cast<uintptr_t>(p) & ~(line - 1), end = reinterpret_cast<uintptr_t>(p) + len;
    for (; a < end; a += line) {
        if (op == 0) __asm__ volatile("dc cvac, %0" :: "r"(a) : "memory");
        else if (op == 1) __asm__ volatile("dc civac, %0" :: "r"(a) : "memory");
        else __asm__ volatile("dc ivac, %0" :: "r"(a) : "memory");
    }
    __asm__ volatile("dsb sy" ::: "memory");
}
void dmaClean(void *, void *p, size_t len) {cacheRange(p, len, 0);}
void dmaCleanInval(void *, void *p, size_t len) {cacheRange(p, len, 1);}
void dmaInval(void *, void *p, size_t len) {cacheRange(p, len, 2);}
uint32_t smmuRd(void *ctx, unsigned o) {return rd32(reinterpret_cast<uintptr_t>(ctx), o);}
void smmuWr(void *ctx, unsigned o, uint32_t v) {wr32(reinterpret_cast<uintptr_t>(ctx), o, v);}

