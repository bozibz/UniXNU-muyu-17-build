// Mappings live for the boot (bring-up probe).
struct Region {IOMemoryMap *keep; uintptr_t va;};

bool mapRegion(uint64_t phys, uint64_t length, Region &region) {
    region.keep = nullptr;
    region.va = 0;
    IODeviceMemory *memory = IODeviceMemory::withRange(phys, length);
    if (!memory) return false;
    region.keep = memory->map(kIOMapAnywhere | kIOMapInhibitCache);
    memory->release();
    if (region.keep) region.va = static_cast<uintptr_t>(region.keep->getVirtualAddress());
    return region.va != 0;
}
uint32_t rd32(uintptr_t base, uint32_t reg) {return *reinterpret_cast<volatile uint32_t *>(base + reg);}
void wr32(uintptr_t base, uint32_t reg, uint32_t value) {
    *reinterpret_cast<volatile uint32_t *>(base + reg) = value;
    __asm__ volatile("dsb sy" ::: "memory");
}
uint32_t ioRd(void *ctx, uint32_t reg) {return rd32(reinterpret_cast<uintptr_t>(ctx), reg);}
void ioWr(void *ctx, uint32_t reg, uint32_t value) {wr32(reinterpret_cast<uintptr_t>(ctx), reg, value);}
void ioDelayUs(void *, unsigned us) {IODelay(us);}

unsigned rowAt;
void row(const char *fmt, ...) __attribute__((format(printf, 1, 2)));
// The panic dump reads msgbuf, not this array, so a full array must never stop the logging: stage 33 on
// 2026-10-25 18:38 lost nine of its twelve rows because the old version returned before IOLog once the
// 24 slots were used.
void row(const char *fmt, ...) {
    char buf[120];
    va_list args;
    va_start(args, fmt);
    vsnprintf(buf, sizeof buf, fmt, args);
    va_end(args);
    IOLog("MUYU TOUCH %s\n", buf);
    if (rowAt < sizeof(native_touch_muyu_rows) / sizeof(native_touch_muyu_rows[0])) {
        for (unsigned i = 0; i < sizeof buf; ++i) {
            native_touch_muyu_rows[rowAt][i] = buf[i];
            if (!buf[i]) break;
        }
    }
    rowAt++;
}

struct Survey {
    Region gcc, tlmm, qup;
    uintptr_t se, wrapper;
    uint32_t vote, voteExtra, haltCore2x, haltCore, haltS4, rcgCmd, rcgCfg, rcgM, rcgN;
    uint32_t pin[4], pinIo[4], irqCtl, irqIo, lcdCtl;
    uint32_t wrapperVer, wrapperParam, seStatus, seFwRev, seHwParam, seSClkCfg, seClkSel;
    bool gccOk, tlmmOk, qupOk;
    struct geni_spi spi;
    int chipRc;
};

bool surveyRead(Survey &s) {
    s.gccOk = mapRegion(TM_GCC_BASE, 0x200000, s.gcc);
    unsigned pins = 1;
    PE_parse_boot_argn("muyu-touch-tlmm", &pins, sizeof(pins));
    s.tlmmOk = pins != 0 && mapRegion(TM_TLMM_BASE, 0x200000, s.tlmm);   // gpio 0..511: gpio177 is reachable
    // One window covers the serial engine and its wrapper. The separate 0xa90000 mapping did not come up on the
    // first probe, while the wrapper range did, so both are read through the same mapping.
    s.qupOk = mapRegion(TM_QUP_WINDOW_BASE, TM_QUP_WINDOW_SIZE, s.qup);
    s.se = s.qupOk ? s.qup.va + TM_QUP_SE_OFFSET : 0;
    s.wrapper = s.qupOk ? s.qup.va + TM_QUP_WRAP_OFFSET : 0;
    if (!s.gccOk) return false;
    s.vote = rd32(s.gcc.va, 0x52008);
    s.voteExtra = rd32(s.gcc.va, 0x52018);
    s.haltCore2x = rd32(s.gcc.va, TM_GCC_HALT_CORE_2X);
    s.haltCore = rd32(s.gcc.va, TM_GCC_HALT_CORE);
    s.haltS4 = rd32(s.gcc.va, TM_GCC_HALT_S4);
    s.rcgCmd = rd32(s.gcc.va, TM_S4_RCG_CMD);
    s.rcgCfg = rd32(s.gcc.va, TM_S4_RCG_CFG);
    s.rcgM = rd32(s.gcc.va, TM_S4_RCG_M);
    s.rcgN = rd32(s.gcc.va, TM_S4_RCG_N);
    if (s.qupOk) {
        s.wrapperVer = rd32(s.wrapper, 0x0);
        s.wrapperParam = rd32(s.wrapper, 0x4);
    }
    return true;
}

// The pin controller is read last: an access to a gated TLMM register is a bus error, and everything printed
// above it stays on the console.
void pinRows(Survey &s) {
    if (!s.tlmmOk) {row("TLMM not mapped (muyu-touch-tlmm=0)"); return;}
    const unsigned spiPins[4] = {TM_GPIO_MISO, TM_GPIO_MOSI, TM_GPIO_CLK, TM_GPIO_CS};
    for (unsigned i = 0; i < 4; i++) {
        s.pin[i] = rd32(s.tlmm.va, tm_tlmm_ctl_reg(spiPins[i]));
        s.pinIo[i] = rd32(s.tlmm.va, tm_tlmm_io_reg(spiPins[i]));
    }
    s.irqCtl = rd32(s.tlmm.va, tm_tlmm_ctl_reg(TM_GPIO_IRQ));
    s.irqIo = rd32(s.tlmm.va, tm_tlmm_io_reg(TM_GPIO_IRQ));
    s.lcdCtl = rd32(s.tlmm.va, tm_tlmm_ctl_reg(TM_GPIO_LCD_ID));
    row("TLMM ctl %u/%u/%u/%u = %08x %08x %08x %08x", TM_GPIO_MISO, TM_GPIO_MOSI, TM_GPIO_CLK, TM_GPIO_CS,
        s.pin[0], s.pin[1], s.pin[2], s.pin[3]);
    row("TLMM mux %u/%u/%u/%u io %08x %08x %08x %08x", (s.pin[0] >> 2) & 7, (s.pin[1] >> 2) & 7,
        (s.pin[2] >> 2) & 7, (s.pin[3] >> 2) & 7, s.pinIo[0], s.pinIo[1], s.pinIo[2], s.pinIo[3]);
    row("TLMM IRQ gpio%u ctl=%08x io=%08x lcd%u ctl=%08x", TM_GPIO_IRQ, s.irqCtl, s.irqIo, TM_GPIO_LCD_ID, s.lcdCtl);
}

void setSpiPins(Survey &s) {
    if (!s.tlmmOk) return;
    const unsigned spiPins[4] = {TM_GPIO_MISO, TM_GPIO_MOSI, TM_GPIO_CLK, TM_GPIO_CS};
    for (unsigned i = 0; i < 4; i++) wr32(s.tlmm.va, tm_tlmm_ctl_reg(spiPins[i]), TM_PIN_SPI_CTL);
    row("TLMM pins set %08x, now ctl %08x %08x %08x %08x", TM_PIN_SPI_CTL,
        rd32(s.tlmm.va, tm_tlmm_ctl_reg(TM_GPIO_MISO)), rd32(s.tlmm.va, tm_tlmm_ctl_reg(TM_GPIO_MOSI)),
        rd32(s.tlmm.va, tm_tlmm_ctl_reg(TM_GPIO_CLK)), rd32(s.tlmm.va, tm_tlmm_ctl_reg(TM_GPIO_CS)));
}

bool readEngine(Survey &s) {
    if (!s.qupOk) {row("QUP window not mapped"); return false;}
    s.seStatus = rd32(s.se, SE_GENI_STATUS);
    s.seFwRev = rd32(s.se, GENI_FW_REVISION_RO);
    s.seHwParam = rd32(s.se, SE_HW_PARAM_0);
    s.seSClkCfg = rd32(s.se, GENI_SER_M_CLK_CFG);
    s.seClkSel = rd32(s.se, SE_GENI_CLK_SEL);
    row("SE status=%08x fwrev=%08x hwparam=%08x sclk=%08x clksel=%08x", s.seStatus, s.seFwRev, s.seHwParam,
        s.seSClkCfg, s.seClkSel);
    return true;
}

// Stage 3: FIFO transfers only; the SE DMA engine and its apps-SMMU stream are not touched.
bool identify(Survey &s, unsigned hz) {
    static uint8_t tx[NVT_TRANSFER_LEN + 8], rx[NVT_READ_MAX + 2];
    struct geni_spi &g = s.spi;
    int rc = geni_spi_read_info(&g);
    row("geni info rc=%d fw=%08x proto=%08x fifo_dis=%d hw=%08x", rc, g.info.fw_revision, g.info.protocol,
        g.info.fifo_disabled, g.info.qup_hw_version);
    if (rc) return false;
    rc = geni_spi_init(&g);
    row("geni init rc=%d oversampling=%u", rc, g.oversampling);
    if (rc) return false;
    rc = geni_spi_set_clock(&g, hz, TM_SPI_HZ, 0);
    row("geni clock rc=%d hz=%u", rc, hz);
    if (rc) return false;
    rc = geni_spi_setup(&g, 0, 0);
    row("geni setup rc=%d", rc);
    if (rc) return false;
    struct nvt_chip chip;
    memset(&chip, 0, sizeof chip);
    struct nvt_bus bus;
    memset(&bus, 0, sizeof bus);
    bus.ctx = &g;
    bus.xfer = [](void *ctx, const uint8_t *out, uint8_t *in, size_t len) -> int {
        struct geni_spi *engine = static_cast<struct geni_spi *>(ctx);
        return geni_spi_transfer(engine, out, in, len, 0) ? -1 : 0;
    };
    bus.delay_ms = [](void *, unsigned ms) {IOSleep(ms);};
    chip.bus = &bus;
    chip.scratch = tx;
    chip.rxbuf = rx;
    s.chipRc = nvt_identify(&chip);
    row("nvt_identify rc=%d id=%02x %02x %02x %02x %02x %02x", s.chipRc, (unsigned)chip.id[0],
        (unsigned)chip.id[1], (unsigned)chip.id[2], (unsigned)chip.id[3], (unsigned)chip.id[4],
        (unsigned)chip.id[5]);
    for (unsigned i = 0; i < 6; i++) native_touch_muyu_chip[i] = chip.id[i];
    return s.chipRc == 0;
}

// Stage 4: read-only. Every serial engine of qupv3_0 (0xa80000 + n*0x4000) plus the GCC QUP vote block,
// so the state the bootloader left behind is visible without writing a register.
void engineTable(Survey &s) {
    if (!s.qupOk) {row("QUP window not mapped"); return;}
    for (unsigned n = 0; n < 8; n++) {
        uintptr_t base = s.qup.va + 0x80000 + n * 0x4000;
        uint32_t fw = rd32(base, GENI_FW_REVISION_RO), st = rd32(base, SE_GENI_STATUS);
        uint32_t idis = rd32(base, GENI_IF_DISABLE_RO), hp = rd32(base, SE_HW_PARAM_0);
        uint32_t sclk = rd32(base, GENI_SER_M_CLK_CFG), sel = rd32(base, SE_GENI_CLK_SEL);
        row("SE%u fw=%08x st=%08x ifdis=%08x hw=%08x sclk=%08x sel=%08x", n, fw, st, idis, hp, sclk, sel);
    }
    row("GCC qup blk %08x %08x %08x %08x %08x %08x %08x %08x", rd32(s.gcc.va, 0x52000), rd32(s.gcc.va, 0x52004),
        rd32(s.gcc.va, 0x52008), rd32(s.gcc.va, 0x5200c), rd32(s.gcc.va, 0x52010), rd32(s.gcc.va, 0x52014),
        rd32(s.gcc.va, 0x52018), rd32(s.gcc.va, 0x5201c));
}

// Chip select: the shared GENI driver clears CS_TOGGLE and relies on the protocol layer to drive CS,
// the way spi-geni-qcom does with the SPI_CS_ASSERT/SPI_CS_DEASSERT commands. Without them the slave
// never answers and every read comes back 0x00 (stage 10, 2026-10-25 14:18).
#define TM_SPI_CS_ASSERT 8u
#define TM_SPI_CS_DEASSERT 9u

int csCommand(uintptr_t se, uint32_t opcode) {
    wr32(se, SE_GENI_M_IRQ_CLEAR, 0xffffffffu);
    wr32(se, SE_GENI_M_CMD0, opcode << 27);
    for (unsigned n = 0; n < 2000; n++) {
        uint32_t st = rd32(se, SE_GENI_M_IRQ_STATUS);
        if (st & 1u) {wr32(se, SE_GENI_M_IRQ_CLEAR, st); return 0;}   // M_CMD_DONE
        IODelay(10);
    }
    return -1;
}

