extern "C" void native_touch_muyu_probe(void);
extern "C" void native_touch_muyu_probe(void) {
    unsigned stage = 0;
    if (!PE_parse_boot_argn("muyu-touch", &stage, sizeof(stage)) || stage < 1) return;
    if (native_touch_muyu_stage) return;
    native_touch_muyu_stage = 1;
    static Survey survey;
    if (!surveyRead(survey)) {native_touch_muyu_error = -1; row("GCC map failed"); return;}
    row("GCC vote=%08x extra=%08x halt c2x=%08x core=%08x s4=%08x", survey.vote, survey.voteExtra,
        survey.haltCore2x, survey.haltCore, survey.haltS4);
    row("GCC branches running: c2x=%u core=%u s4=%u", (unsigned)!(survey.haltCore2x & TM_CBCR_CLK_OFF),
        (unsigned)!(survey.haltCore & TM_CBCR_CLK_OFF), (unsigned)!(survey.haltS4 & TM_CBCR_CLK_OFF));
    row("SE4 rcg cmd=%08x cfg=%08x m=%08x n=%08x src=%u", survey.rcgCmd, survey.rcgCfg, survey.rcgM, survey.rcgN,
        (survey.rcgCfg >> 8) & 7);
    row("QUP wrapper ver=%08x param=%08x", survey.wrapperVer, survey.wrapperParam);
    native_touch_muyu_step = 1;
    if (stage >= 6) {writeStages(survey, stage); return;}
    pinRows(survey);
    if (stage < 2) return;
    if (!readEngine(survey)) {native_touch_muyu_error = -2; return;}
    native_touch_muyu_step = 2;
    if (stage == 4) {engineTable(survey); native_touch_muyu_step = 4; return;}
    if (stage == 5) {
        // One write per boot, addressed by the boot arguments, so the register that resets the board can be
        // found without rebuilding the kernel each time. No engine sweep here: reading a serial engine whose
        // clock is gated is itself a bus error (measured 2026-10-25 11:56), so only the one engine named by
        // muyu-touch-se is touched.
        unsigned where = 0, value = 0, seIndex = 4, hold = 0;
        PE_parse_boot_argn("muyu-touch-w", &where, sizeof(where));
        PE_parse_boot_argn("muyu-touch-v", &value, sizeof(value));
        PE_parse_boot_argn("muyu-touch-se", &seIndex, sizeof(seIndex));
        PE_parse_boot_argn("muyu-touch-hold", &hold, sizeof(hold));
        if (seIndex > 7) seIndex = 4;
        uintptr_t engine = survey.qup.va + 0x80000 + seIndex * 0x4000;
        row("write test: SE%u+%03x value=%08x before=%08x", seIndex, where & 0xfff, value,
            rd32(engine, where & 0xfff));
        if (hold) {
            row("holding %us before the write (photograph now)", hold);
            IOSleep(hold * 1000);
        }
        wr32(engine, where & 0xfff, value);
        IODelay(200);
        row("write test: after=%08x", rd32(engine, where & 0xfff));
        native_touch_muyu_step = 5;
        return;
    }
    if (stage < 3) return;
    setSpiPins(survey);
    survey.spi.se.ctx = reinterpret_cast<void *>(survey.se);
    survey.spi.se.rd = ioRd;
    survey.spi.se.wr = ioWr;
    survey.spi.se.delay_us = ioDelayUs;
    survey.spi.wrapper.ctx = reinterpret_cast<void *>(survey.wrapper);
    survey.spi.wrapper.rd = ioRd;
    survey.spi.poll_limit = 200000;
    survey.spi.poll_only = 2;
    survey.spi.allow_fifo_disabled = 1;   // FIFO is the only path this probe offers
    survey.spi.use_dma = 0;
    unsigned hz = TM_SPI_HZ;
    PE_parse_boot_argn("muyu-touch-hz", &hz, sizeof(hz));
    if (hz < 100000 || hz > TM_SPI_HZ) hz = TM_SPI_HZ;
    if (!identify(survey, hz)) {native_touch_muyu_error = -3; return;}
    native_touch_muyu_step = 3;
}
