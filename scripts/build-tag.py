#!/usr/bin/env python3
"""The build tag for a kernel round: one name, one place.

    scripts/build-tag.py next --purpose scr        # 27-scr-1108a, writes BUILD-TAG
    scripts/build-tag.py cflag                     # -DMUYU_BUILD_TAG='"27-scr-1108a"'
    scripts/build-tag.py names                    # vendor_boot_27-scr-1108a.img, ...
    scripts/build-tag.py check build/.../x.a      # fails if the object still says "untagged"

Naming: <line>-<purpose>-<MMDD><letter> (docs/BUILD-NAMING.md). The u-counter is retired: it
carried no information about what changed, and it was written by hand into printfs, which is how
the u151-u159 reconstruction drew a wrong conclusion on 2026-11-08.

The tag lives in BUILD-TAG (one line). It reaches the kernel as build_tag_generated.h next to
build_tag.h - no build-system change, and never through the command line: kernel_args is at
979 B of a ~1000 B budget. -DMUYU_BUILD_TAG is there for builds that can pass flags.
"""
import argparse
import datetime
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
TAGFILE = ROOT / 'BUILD-TAG'
LEDGER = ROOT / 'BUILD-TAGS.tsv'
HEADER = ROOT / 'drivers/MuyuDebug/build_tag_generated.h'

PURPOSES = {
    'scr': 'screen / observation path (console page, paging, panic replay)',
    'cfg': 'configuration, defconfig, link set',
    'sto': 'storage, Data, cryptex, keybag',
    'gpu': 'GPU, GMU, Adreno',
    'inp': 'touch, buttons, HID',
    'usr': 'userland, launchd, dyld, shared cache',
    'pwr': 'power, thermal, backlight',
    'net': 'network',
}
TAG_RE = re.compile(r'^(17|27)-(scr|cfg|sto|gpu|inp|usr|pwr|net)-(\d{4})([a-z]{1,2})$')


def current():
    if not TAGFILE.exists():
        return None
    tag = TAGFILE.read_text().strip()
    return tag or None


def bump(letter):
    if len(letter) == 1 and letter < 'z':
        return chr(ord(letter) + 1)
    if len(letter) == 1:
        return 'aa'
    head, tail = letter[0], letter[1]
    if tail < 'z':
        return head + chr(ord(tail) + 1)
    return chr(ord(head) + 1) + 'a'


def resolve_arm_dir(tree):
    """The kernel source tree's bsd/dev/arm: either <tree>/bsd/dev/arm or the cached working copy."""
    root = pathlib.Path(tree)
    for cand in (root / 'bsd/dev/arm', root / '.cache/xnu-work/bsd/dev/arm'):
        if cand.is_dir():
            return cand
    return None


def emit(tag, tree=None):
    """Write BUILD-TAG and the generated header the kernel includes."""
    TAGFILE.write_text(tag + '\n')
    HEADER.write_text(
        '/* Generated by scripts/build-tag.py - do not edit, do not commit a stale copy.\n'
        f' * {tag}\n'
        ' */\n'
        f'#define MUYU_BUILD_TAG "{tag}"\n')
    if tree:
        dest = resolve_arm_dir(tree)
        if dest is None:
            sys.exit(f'build-tag: no bsd/dev/arm under {tree} (looked at bsd/dev/arm and .cache/xnu-work/bsd/dev/arm)')
        for name in ('build_tag.h', 'build_tag_generated.h'):
            (dest / name).write_bytes((HEADER.parent / name).read_bytes())
        print(f'build-tag: headers installed in {dest}', file=sys.stderr)


def cmd_next(args):
    day = args.date or datetime.date.today().strftime('%m%d')
    prev = current()
    letter = 'a'
    if prev:
        m = TAG_RE.match(prev)
        if m and m.group(1) == args.line and m.group(2) == args.purpose and m.group(3) == day:
            letter = bump(m.group(4))
    tag = f'{args.line}-{args.purpose}-{day}{letter}'
    emit(tag, args.tree)
    with LEDGER.open('a') as out:
        out.write(f'{datetime.datetime.now().isoformat(timespec="seconds")}\t{tag}\t{args.purpose}\t{args.note}\n')
    print(tag)
    return 0


def cmd_set(args):
    tag = args.tag.strip()
    if not TAG_RE.match(tag):
        sys.exit(f'build-tag: {tag!r} does not match <line>-<purpose>-<MMDD><letter>')
    emit(tag, args.tree)
    print(tag)
    return 0


def cmd_show(args):
    tag = current()
    if not tag:
        sys.exit('build-tag: BUILD-TAG is missing; run: scripts/build-tag.py next --purpose scr')
    print(tag)
    return 0


def cmd_cflag(args):
    tag = current()
    if not tag:
        sys.exit('build-tag: BUILD-TAG is missing; run: scripts/build-tag.py next --purpose scr')
    # Single quotes so the shell keeps the inner double quotes: -DMUYU_BUILD_TAG='"27-scr-1108a"'
    print(f"-DMUYU_BUILD_TAG='\"{tag}\"'")
    return 0


def cmd_names(args):
    tag = current()
    if not tag:
        sys.exit('build-tag: BUILD-TAG is missing; run: scripts/build-tag.py next --purpose scr')
    for stem in ('vendor_boot', 'boot', 'kernel'):
        print(f'{stem}_{tag}.img' if stem != 'kernel' else f'kernel_{tag}.macho')
    return 0


def cmd_check(args):
    data = pathlib.Path(args.path).read_bytes()
    # "untagged" alone is a common English word inside a kernel; only our two output forms count.
    if b'(untagged)' in data or b'MUYU untagged' in data:
        sys.exit(f'build-tag: {args.path} still prints the fallback tag - the build did not see BUILD-TAG '
                 f'or -DMUYU_BUILD_TAG')
    old = re.findall(rb'\(u1\d\d\)', data)
    if old:
        print(f'build-tag: warning: {args.path} still prints a u-counter tag: '
              + ', '.join(sorted({b.decode() for b in old})))
    print(f'build-tag: {args.path} has no fallback tag (ok)')
    return 0


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest='cmd', required=True)

    n = sub.add_parser('next', help='allocate the next tag and write BUILD-TAG')
    n.add_argument('--purpose', required=True, choices=sorted(PURPOSES))
    n.add_argument('--line', default='27', choices=['17', '27'])
    n.add_argument('--date', help='MMDD override, for replaying an older round')
    n.add_argument('--note', default='', help='free text for BUILD-TAGS.tsv')
    n.add_argument('--tree', help='build tree to install build_tag*.h into (…/tree)')
    n.set_defaults(func=cmd_next)

    s = sub.add_parser('set', help='write an explicit tag')
    s.add_argument('tag')
    s.add_argument('--tree', help='build tree to install build_tag*.h into (…/tree)')
    s.set_defaults(func=cmd_set)

    sh = sub.add_parser('show', help='print the current tag')
    sh.set_defaults(func=cmd_show)

    c = sub.add_parser('cflag', help='print the compiler flag for the current tag')
    c.set_defaults(func=cmd_cflag)

    nm = sub.add_parser('names', help='print the artifact names for the current tag')
    nm.set_defaults(func=cmd_names)

    ck = sub.add_parser('check', help='verify an object/archive carries a real tag')
    ck.add_argument('path')
    ck.set_defaults(func=cmd_check)

    args = p.parse_args()
    return args.func(args)


if __name__ == '__main__':
    sys.exit(main())
