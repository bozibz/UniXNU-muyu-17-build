#!/usr/bin/env python3
"""Generate muyu's GPU SMMU binding (ShengGpuSmmuSource.h) from pinned inputs; no device I/O.

ShengGpuSmmu.c is board-agnostic but includes a generated header that sheng produces from its DTB and
a pinned copy of the Qualcomm SMMU driver. This is the muyu counterpart.

Inputs, all local:
  UniXNU-muyu/build/gpu/muyu-gpu-platform.json     SMMU base/size, GMU stream, interrupt count
  fw/android-harvest/vendor-source/arm-smmu-qcom.c the vendor's context-bank policy for this SoC
  fw/stock/dtb_3.dtb                               the devicetree those facts came from

Why the bank policy matters: on this SoC the vendor driver gives the *GPU device two* context banks
(banks 0 and 1, "so the GPU hardware can switch pagetables") and hands everything else banks 2..N-1.
sheng's policy only reserves bank 0. Copying sheng's "first free bank" would put the GMU on bank 1,
which belongs to the GPU here.

usage: gen-muyu-gpu-smmu-source.py [--out DIR]
"""
import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PLATFORM_SCRIPT = "gen-muyu-gpu-platform.py"


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "UniXNU-muyu/build/gpu"))
    ap.add_argument("--dtb", default=str(ROOT / "fw/stock/dtb_3.dtb"))
    ap.add_argument("--vendor-source", default=str(ROOT / "fw/android-harvest/vendor-source"))
    args = ap.parse_args(argv[1:])

    # Regenerate the platform description so this header always matches the DTB it cites.
    subprocess.run([sys.executable, str(ROOT / "UniXNU-muyu/scripts" / PLATFORM_SCRIPT), "--dtb", args.dtb],
                   check=True, capture_output=True)
    platform_path = ROOT / "UniXNU-muyu/build/gpu/muyu-gpu-platform.json"
    platform = json.loads(platform_path.read_text())
    smmu = platform["smmu"]
    base, size = smmu["regions"]["base"]["base"], smmu["regions"]["base"]["size"]
    gmu_sid = smmu["stream"]
    if (base, size) != (0x03DA0000, 0x40000):
        raise SystemExit(f"unexpected GPU SMMU range {base:#x}+{size:#x}")
    if gmu_sid != 5:
        raise SystemExit(f"unexpected GMU stream id {gmu_sid}")

    # Vendor context-bank policy for this SoC.
    source = Path(args.vendor_source) / "arm-smmu-qcom.c"
    text = source.read_text()
    block = text[text.index("static int qcom_adreno_smmu_alloc_context_bank("):
                 text.index("static bool qcom_adreno_can_do_ttbr1(", text.index("static int qcom_adreno_smmu_alloc_context_bank("))]
    if not re.search(r"if \(qcom_adreno_smmu_is_gpu_device\(dev\)\) \{\s*start = 0;\s*count = (\d+);", block):
        raise SystemExit("vendor policy no longer reserves bank 0 for the GPU device")
    gpu_banks = int(re.search(r"count = (\d+);", block).group(1))
    other = re.search(r"else \{\s*start = (\d+);\s*count = smmu->num_context_banks;", block)
    if not other:
        raise SystemExit("vendor policy no longer starts other devices at a fixed bank")
    first_other_bank = int(other.group(1))
    if gpu_banks != 2 or first_other_bank != 2:
        raise SystemExit(f"bank policy changed: gpu banks {gpu_banks}, first other bank {first_other_bank}")
    if "reg |= ARM_SMMU_SCTLR_HUPCF;" not in text:
        raise SystemExit("Adreno fault-continuation policy changed")

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    header = out / "ShengGpuSmmuSource.h"
    header.write_text(
        "/* Generated by UniXNU-muyu/scripts/gen-muyu-gpu-smmu-source.py. Do not commit. */\n"
        "#include <stdint.h>\n"
        f"#define SHENG_GPU_SMMU_BASE UINT64_C({base:#x})\n"
        f"#define SHENG_GPU_SMMU_BYTES {size}u\n"
        "#define SHENG_GPU_SMMU_GPU_STREAMS 2u\n"
        f"#define SHENG_GPU_SMMU_GMU_SID {gmu_sid}u\n"
        "static const uint16_t sheng_gpu_smmu_sids[2]={0,1};\n"
        "/* muyu-specific: the GPU owns context banks 0 and 1 (vendor arm-smmu-qcom.c), so the GMU\n"
        " * must take a bank from 2 upwards. */\n"
        f"#define SHENG_GPU_SMMU_GPU_BANK 0u\n"
        f"#define SHENG_GPU_SMMU_GPU_BANKS {gpu_banks}u\n"
        f"#define SHENG_GPU_SMMU_GMU_BANK_MIN {first_other_bank}u\n")
    report = dict(smmu=dict(base=f"{base:#x}", bytes=f"{size:#x}", gmu_sid=gmu_sid,
                            gpu_sids=[0, 1], gpu_bank=0, gpu_banks=gpu_banks,
                            gmu_bank_min=first_other_bank),
                  irq_spis=len(smmu["irq_spis"]),
                  vendor_policy_sha256=sha(source),
                  platform_report_sha256=sha(platform_path),
                  header_sha256=sha(header),
                  source_analysis_only=True, hardware_registers_observed=False)
    (out / "muyu-gpu-smmu-source-report.json").write_text(json.dumps(report, indent=2) + "\n")

    print(f"GPU SMMU {base:#x}+{size:#x}: GPU banks 0..{gpu_banks - 1} (SIDs 0/1), "
          f"GMU SID {gmu_sid} must use bank >= {first_other_bank}")
    print(f"wrote {header}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
