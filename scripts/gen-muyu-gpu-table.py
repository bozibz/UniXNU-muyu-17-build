#!/usr/bin/env python3
"""Emit the `[gpu]` board table from the derived inputs, and check board.toml against it.

Why generated instead of typed: every value in the table already exists in exactly one place
(`scripts/data/muyu-gpu-inputs.json`, itself derived from `fw/dtb_04.dtb` plus the pinned upstream
profile). A hand-written copy drifts the moment the DTB or the profile changes, and the drift only
shows up as a wrong register write on the tablet.

    scripts/gen-muyu-gpu-table.py              # print the block
    scripts/gen-muyu-gpu-table.py --check      # exit 1 if board.toml's [gpu] differs from the inputs
    scripts/gen-muyu-gpu-table.py --write      # replace the block between the BEGIN/END markers

The key names are uke's (UniXNU-uke c7aefb9 `[gpu]`), so the same prepare script can read either board.
Keys whose value is a *guess for this board* (the two GMU clock targets and the reserved pool) are
called out in the emitted comments instead of being silently presented as facts.

Host-only, no device I/O.
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

try:                                  # 3.11+; the block text comparison below does not need it
    import tomllib
except ModuleNotFoundError:           # the system python3 on this Mac is 3.9
    tomllib = None

ROOT = Path(__file__).resolve().parents[1]
WORKSPACE = ROOT.parent
INPUTS = ROOT / 'scripts/data/muyu-gpu-inputs.json'
BOARD = ROOT / 'board.toml'
FIRMWARE = WORKSPACE / 'fw/gpu-firmware'
BEGIN = '# >>> gpu table (generated by scripts/gen-muyu-gpu-table.py; do not edit by hand)'
END = '# <<< gpu table'

# uke's GMU clock targets and reserved pool, adopted as the starting point and marked as such: they are
# the A732 numbers on the same GPUCC, not measurements of this tablet.
GMU_CORE_HZ = 220000000
GMU_HUB_HZ = 200000000
GMU_POOL_BASE = 0xc8000000
GMU_POOL_BYTES = 0x2000000


def table():
    record = json.loads(INPUTS.read_text())
    chip, board, opp, profile = record['chip'], record['board'], record['opp'], record['profile']
    if profile is None:
        raise SystemExit(f'{INPUTS}: no pinned chip profile for {chip["chip_id"]}')
    gpu = board['gpu']['kgsl_3d0_reg_memory']
    gmu = board['gmu']['gmu']
    pdc = board['gmu']['gmu_pdc']
    smmu = board['smmu']['window0']
    freqs = [level['hz'] // 1000000 for level in opp['levels']]
    pins = {}
    for name in ('gen71100_sqe.fw', 'gen71100_gmu.bin', 'gen71100_zap.mbn'):
        path = FIRMWARE / name
        if path.is_file():
            pins[name] = (path.stat().st_size, hashlib.sha256(path.read_bytes()).hexdigest())
    values = {
        'model': chip['model'],
        'chip_id': chip['chip_id'],
        'compatible': chip['compatible'],
        'family': chip['family'],
        'gpu_base': hex(gpu['base']),
        'gpu_size': hex(gpu['bytes']),
        'gmu_base': hex(gmu['base']),
        'gmu_size': hex(gmu['bytes']),
        'gmu_pdc_base': hex(pdc['base']),
        'gmu_pdc_size': hex(pdc['bytes']),
        'gpucc_base': hex(board['gpucc']['base']),
        'gpucc_size': hex(board['gpucc']['bytes']),
        'gcc_base': hex(board['gcc']['base']),
        'smmu_base': hex(smmu['base']),
        'smmu_size': hex(smmu['bytes']),
        'sid_user': hex(board['sid_user']),
        'sid_secure': hex(board['sid_secure']),
        'sid_gmu': hex(board['sid_gmu']),
        'gmem_bytes': hex(profile['gmem_bytes']),
        'gmu_chip_id': hex(profile['gmu_chip_id']),
        'gmu_cgc_mode': '0x%08x' % profile['gmu_cgc_mode'],
        'preempt_record_bytes': hex(profile['preempt_record_bytes']),
        'gmu_pool_base': hex(GMU_POOL_BASE),
        'gmu_pool_bytes': hex(GMU_POOL_BYTES),
        'ubwc_version': profile['ubwc_version'],
        'ubwc_swizzle': profile['ubwc_swizzle'],
        'highest_bank_bit': profile['highest_bank_bit'],
        'gmu_core_clock_hz': GMU_CORE_HZ,
        'gmu_hub_clock_hz': GMU_HUB_HZ,
        'frequencies_mhz': freqs,
        'num_pwrlevels': len(freqs),
        'initial_pwrlevel': opp['initial_pwrlevel'],
        'min_pwrlevel': opp['initial_pwrlevel'],
        'max_pwrlevel': 0,
        'firmware_sqe': [profile['firmware']['sqe'], 'gen71500_sqe.fw'],
        'firmware_gmu': [profile['firmware']['gmu'], 'gen71500_gmu.bin'],
        'firmware_zap': [profile['firmware']['zap'], 'gen71500_zap.mbn'],
        'firmware_source': 'extracted from muyu /vendor/firmware (fw/gpu-firmware)',
    }
    return values, pins, record


def quote(value):
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, str):
        return f'"{value}"'
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return '[' + ', '.join(quote(item) for item in value) + ']'
    raise SystemExit(f'cannot emit {value!r}')


def render():
    values, pins, record = table()
    lines = [
        BEGIN,
        '# Adreno 735 (SM8635 cliffs). Every value below is derived from fw/dtb_04.dtb or copied from the',
        '# pinned upstream chip profile (scripts/data/adreno-profiles.json); regenerate instead of editing.',
        '# The native driver is not in the kernel build yet - see docs/GPU-UKE-ALIGNMENT.md.',
        '[gpu]',
    ]
    for key, value in values.items():
        lines.append(f'{key} = {quote(value)}')
    for name, (size, digest) in pins.items():
        lines.append('')
        lines.append(f'[gpu.firmware_pins."{name}"]')
        lines.append(f'bytes = {size}')
        lines.append(f'sha256 = "{digest}"')
    lines += [
        '',
        '# Reserved: the ADT needs a matching gmu-memory node and the UEFI memory map a matching',
        '# "GMU Pool" entry (uke: 0xC8000000 / 32 MiB). Both are still to be added on this board.',
        END + f'  # profile {record["profile"]["name"]} @ {record["profile"]["source"]["commit"][:12]}',
    ]
    return '\n'.join(lines) + '\n'


def block_of(text):
    if BEGIN not in text:
        return None
    start = text.index(BEGIN)
    end = text.index(END, start)
    end = text.index('\n', end) + 1
    return text[start:end]


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--check', action='store_true', help='verify board.toml carries this block')
    group.add_argument('--write', action='store_true', help='replace the block in board.toml')
    args = parser.parse_args()
    generated = render()
    text = BOARD.read_text()
    if args.write:
        current = block_of(text)
        if current is None:
            raise SystemExit(f'{BOARD}: no "{BEGIN}" marker to replace')
        BOARD.write_text(text.replace(current, generated))
        print(f'{BOARD}: [gpu] replaced ({len(generated)} bytes)')
        return
    if args.check:
        current = block_of(text)
        if current is None:
            raise SystemExit(f'{BOARD}: no generated [gpu] block; run --write once')
        if current != generated:
            sys.exit(f'{BOARD}: [gpu] block differs from the derived inputs; run --write')
        values, _pins, _record = table()
        if tomllib is None:
            print(f'{BOARD}: [gpu] block text matches the derived inputs ({len(values)} keys; '
                  f'tomllib unavailable, values not re-parsed)')
            return
        board = tomllib.loads(text)['gpu']
        for key, value in values.items():
            if board.get(key) != value:
                sys.exit(f'{BOARD}: [gpu] {key} is {board.get(key)!r}, expected {value!r}')
        print(f'{BOARD}: [gpu] matches the derived inputs ({len(values)} keys)')
        return
    print(generated, end='')


if __name__ == '__main__':
    main()
