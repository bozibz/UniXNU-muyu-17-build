#!/usr/bin/env python3
"""Generate package/OwnerBootIdentity.h for this board's iPadOS 27 line.

Three values bind the running kernel to one owner boot set, and all three are ours to choose because
the bring-up identity is synthetic on this port (the 17.7.11 line used SHA-384("UkeBringup.BootSet.v1\\0")
for the same field). What must hold is that the three places agree:

  * `[payload.adt] boot_manifest_hash` in board.toml, handed to the ADT as /chosen/boot-manifest-hash
  * `owner_boot_set_hash` in the generated header
  * `owner_boot_set_domain`, read from /chosen/owner-boot-manifest-domain

The two per-policy digests are *not* synthetic: they are the sha256 of each generated envelope's signed
header (VR_HEADER_BYTES + VR_SIGNATURE_BYTES = 544 bytes), so a policy rebuilt for another OS changes them
and the loader refuses the old bundle.

    scripts/gen-muyu-owner-identity.py --policy-dir <dir with OS/ and SystemOS/>
    scripts/gen-muyu-owner-identity.py --print   # show the values without writing

Host only, no device I/O.
"""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER_BYTES = 160 + 384          # vr header + RSA-3072 signature, see kits/VerifiedRoot/include/verified_root.h
BOOT_SET = 'MuyuBringup.BootSet.27'      # the identity this port publishes
# The domain is the ASCII name of the owner boot set (uke's 27 line publishes "VerifiedRoot.OwnerBootSet.v1"),
# not a digest: the loader compares it byte for byte against /chosen/owner-boot-manifest-domain.
DOMAIN = 'MuyuBringup.OwnerBootSet.v1'
ORDER = ('OS', 'SystemOS')


def digest_of(path):
    return hashlib.sha256(path.read_bytes()[:HEADER_BYTES]).digest()


def c_array(name, values):
    body = ',\n    '.join('{' + ', '.join(f'0x{byte:02x}' for byte in chunk) + '}' for chunk in values)
    return f'static const uint8_t {name}[{len(values)}][32] = {{\n    {body},\n}};\n'


def c_bytes(name, data):
    return ('static const uint8_t ' + name + f'[{len(data)}] = {{'
            + ', '.join(f'0x{byte:02x}' for byte in data) + '};\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--policy-dir', type=Path, help='directory holding OS/ and SystemOS/ envelopes')
    parser.add_argument('--out', type=Path, default=ROOT / 'package/OwnerBootIdentity.h')
    parser.add_argument('--print', action='store_true', help='print the values and the header to stdout')
    args = parser.parse_args()
    boot_set_hash = hashlib.sha384((BOOT_SET + '\0').encode()).digest()
    domain = (DOMAIN + '\0').encode()
    digests = []
    if args.policy_dir:
        for name in ORDER:
            manifest = args.policy_dir / name / 'manifest.bin'
            if not manifest.is_file():
                raise SystemExit(f'{manifest} is missing: run build-owner-os-policy.py for {name} first')
            digests.append(digest_of(manifest))
    else:
        digests = [bytes(32)] * len(ORDER)
    print(f'boot_set_hash (sha384 of {BOOT_SET!r} + NUL): {boot_set_hash.hex()}')
    print(f'domain        (ASCII {DOMAIN!r} + NUL): {domain.hex()}')
    for name, digest in zip(ORDER, digests):
        print(f'{name} signed-header sha256: {digest.hex()}')
    header = ('/* Generated by scripts/gen-muyu-owner-identity.py; do not edit. */\n'
              '#pragma once\n#include <stdint.h>\n\n'
              '/* /chosen/boot-manifest-hash and [payload.adt] boot_manifest_hash must carry this value. */\n'
              + c_bytes('owner_boot_set_hash', boot_set_hash)
              + '\n/* /chosen/owner-boot-manifest-domain must carry this value. */\n'
              + c_bytes('owner_boot_set_domain', domain)
              + '\n/* sha256 of each policy envelope\'s signed header, in OS, SystemOS order. */\n'
              + c_array('owner_policy_header_sha256', digests))
    if args.print:
        print(header)
        return
    args.out.write_text(header)
    print(f'wrote {args.out}')


if __name__ == '__main__':
    main()
