#!/usr/bin/env python3
"""Generate the A735 (gen7-11-0) hardware-init table from harvested vendor sources.

The toolchain's A740 table is generated from the pinned upstream sources, which are not present
in this workspace. The device harvest is, and for A735 it is authoritative:

  fw/android-harvest/msm-drv/a7xx_catalog.c   a730_hwcg  (A735 uses the a730 family entry with
                                                          gmu_chipid 0x07110000)
  fw/android-harvest/msm-regs/a6xx.xml        register offsets, A7XX variants
  fw/android-harvest/msm-regs/a6xx_gmu.xml    GMU-side register offsets

Only the hwcg *values* differ between A735 and A740; the offsets are the same A7XX map, which this
script re-derives so the two tables can be compared name by name.

usage: gen-muyu-a735-hwinit.py [--check]
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "fw/android-harvest/msm-drv/a7xx_catalog.c"
MSM_REGS = ROOT / "fw/android-harvest/msm-regs"
OUT = ROOT / "UniXNU-muyu/package/MuyuA735HwInit.h"

ORDER = ["A2XX", "A3XX", "A4XX", "A5XX", "A6XX", "A7XX", "A8XX"]


def matches(variants):
    if variants is None:
        return True
    for part in variants.split(","):
        part = part.strip()
        if "-" in part:
            left, right = part.split("-", 1)
            low = ORDER.index(left) if left else 0
            high = ORDER.index(right) if right else len(ORDER) - 1
            if low <= ORDER.index("A7XX") <= high:
                return True
        elif part == "A7XX":
            return True
    return False


def resolve(name, texts):
    hits = set()
    for text in texts:
        for m in re.finditer(
                r'<reg(?:32|64) offset="(0x[0-9a-fA-F]+)" name="' + name + r'"([^>]*)>', text):
            v = re.search(r'variants="([^"]+)"', m.group(2))
            if matches(v.group(1) if v else None):
                hits.add(int(m.group(1), 16))
    if len(hits) > 1:
        raise SystemExit("ambiguous register " + name + ": " + str(sorted(hits)))
    if not hits:
        raise SystemExit("missing register " + name)
    return hits.pop()


def hwcg_block(catalog):
    m = re.search(r'a730_hwcg\[\]\s*=\s*\{(.*?)\{\},\s*\};', catalog, re.S)
    if not m:
        raise SystemExit("a730_hwcg block not found")
    rows = re.findall(r'\{\s*REG_A[67]XX_([A-Z0-9_]+),\s*(0x[0-9a-fA-F]+)\s*\}', m.group(1))
    if len(rows) != m.group(1).count("REG_"):
        raise SystemExit("unparsed a730_hwcg entry")
    return [(n, int(v, 16)) for n, v in rows]


def render(rows, regs):
    out = ["/* SPDX-License-Identifier: MIT */",
           "#ifndef MUYU_A735_HW_INIT_H",
           "#define MUYU_A735_HW_INIT_H",
           "",
           "/* Generated by UniXNU-muyu/scripts/gen-muyu-a735-hwinit.py from",
           " *   fw/android-harvest/msm-drv/a7xx_catalog.c (a730_hwcg)",
           " *   fw/android-harvest/msm-regs/a6xx.xml, a6xx_gmu.xml (A7XX variants)",
           " * Dword register offsets. Do not edit by hand.",
           " *",
           " * A735 (gen7-11-0) is the a730-family entry (gmu_chipid 0x07110000). Its register",
           " * offsets are the same A7XX map as A740; the hwcg value table is the difference.",
           " */"]
    for name in sorted(regs):
        out.append("#define MUYU_A735_%s 0x%05x" % (name, regs[name]))
    out.append("")
    out.append("static const uint32_t MuyuA735Hwcg[][2]={")
    for name, value in rows:
        out.append("    {MUYU_A735_%s,0x%08x}," % (name, value))
    out.append("};")
    out.append("#define MUYU_A735_HWCG_COUNT %d" % len(rows))
    out.append("")
    out.append("#endif /* MUYU_A735_HW_INIT_H */")
    return "\n".join(out) + "\n"


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv[1:])

    catalog = CATALOG.read_text()
    rows = hwcg_block(catalog)
    texts = [(MSM_REGS / "a6xx.xml").read_text(), (MSM_REGS / "a6xx_gmu.xml").read_text()]
    regs = {name: resolve(name, texts) for name, _ in rows}
    text = render(rows, regs)

    if args.check:
        current = OUT.read_text() if OUT.is_file() else ""
        if current != text:
            print(OUT.name + ": stale; run gen-muyu-a735-hwinit.py")
            return 1
        print("A735 hwinit: OK (%d hwcg entries)" % len(rows))
        return 0
    OUT.write_text(text)
    print("wrote %s (%d hwcg entries)" % (OUT, len(rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
